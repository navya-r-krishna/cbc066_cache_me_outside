"""InterviewIQ - Prompt Engineering Module

Defines structured prompts for question generation, regeneration, and skill
classification, along with anti-injection protections and Pydantic schemas.
"""
from __future__ import annotations

import json
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

import config

PROMPT_VERSION = "2"

# Level calibration examples (for prompt calibration only, never to be reused as generated questions)
LEVEL_CALIBRATION_EXAMPLES = {
    "easy": "What problem does Pydantic solve in FastAPI request handling?",
    "medium": "A nightly job that loads 2M rows into a reporting table slowed from 5 to 40 minutes. How would you find the cause?",
    "hard": "Design a retry and idempotency strategy for a payment webhook consumer that must never double-charge, even during partial outages.",
}

# ---- Pydantic Schemas for Gemini Structured Output ------------------------

class RawGeneratedQuestion(BaseModel):
    """Schema for a single question generated by Gemini."""
    skill: str = Field(description="The technical skill this question primarily tests")
    difficulty: str = Field(description="The difficulty level: 'easy', 'medium', or 'hard'")
    question: str = Field(description="The interview question text tailored to the role and skill")
    key_points: List[str] = Field(
        description="3 to 5 bullet points expected in a strong answer",
        min_length=2,
        max_length=6
    )


class QuestionBatchResponse(BaseModel):
    """Schema for a collection of questions generated in one call."""
    questions: List[RawGeneratedQuestion] = Field(description="List of tailored interview questions")


class SingleQuestionResponse(BaseModel):
    """Schema for a single regenerated replacement question."""
    skill: str = Field(description="The technical skill being tested")
    difficulty: str = Field(description="The difficulty level: 'easy', 'medium', or 'hard'")
    question: str = Field(description="The newly generated replacement interview question")
    key_points: List[str] = Field(
        description="3 to 5 expected key points for the answer",
        min_length=2,
        max_length=6
    )


class SkillClassificationResponse(BaseModel):
    """Schema for classifying an unknown skill into a competency."""
    skill: str = Field(description="The technical skill")
    suggested_competency: str = Field(description="The mapped competency name")
    confidence: float = Field(description="Confidence score between 0.0 and 1.0", ge=0.0, le=1.0)


# ---- Helper for Sanitizing Untrusted Inputs ------------------------------

def _sanitize_untrusted(val: Any) -> str:
    """Format untrusted user text safely as JSON string to mitigate prompt injection."""
    if isinstance(val, (dict, list)):
        return json.dumps(val, ensure_ascii=False)
    return json.dumps(str(val or ""), ensure_ascii=False)


# ---- Prompt A: Interview Question Generation -----------------------------

def build_question_generation_prompt(
    job_title: str,
    job_summary: str,
    requested_slots: List[Dict[str, Any]],  # [{"competency": "...", "skill": "...", "difficulty": "...", "count": 1}]
    candidate_band: str,
    candidate_strengths: List[str],
    candidate_gaps: List[str],
    exclusions: Optional[List[str]] = None,
) -> str:
    """Constructs Prompt A for generating interview questions.

    Args:
        job_title: Title of the job
        job_summary: Short summary of the JD
        requested_slots: List of (competency, skill, difficulty, count) requests
        candidate_band: Experience level ('beginner', 'intermediate', 'advanced')
        candidate_strengths: Candidate's verified strong skills
        candidate_gaps: Candidate's skill gaps
        exclusions: Question texts to avoid duplicating
    """
    total_requested = sum(slot.get("count", 1) for slot in requested_slots)

    slots_breakdown = []
    for slot in requested_slots:
        c = slot.get("competency", "")
        s = slot.get("skill", "")
        d = slot.get("difficulty", "medium")
        cnt = slot.get("count", 1)
        slots_breakdown.append(f"- Skill: '{s}' (Competency: '{c}') | Difficulty: {d} | Count: {cnt}")

    slots_text = "\n".join(slots_breakdown)

    exclusions_list = [q for q in (exclusions or []) if q.strip()]
    exclusions_text = ""
    if exclusions_list:
        exclusions_text = "EXCLUDED QUESTIONS (DO NOT generate these or close paraphrases):\n" + "\n".join(
            f"- {q}" for q in exclusions_list[:15]
        ) + "\n\n"

    calibration_text = ""
    if getattr(config, "INCLUDE_LEVEL_EXAMPLES", True):
        calibration_text = (
            "CALIBRATION EXAMPLES (for calibration only, never reuse):\n"
            f"- easy: \"{LEVEL_CALIBRATION_EXAMPLES['easy']}\"\n"
            f"- medium: \"{LEVEL_CALIBRATION_EXAMPLES['medium']}\"\n"
            f"- hard: \"{LEVEL_CALIBRATION_EXAMPLES['hard']}\"\n\n"
        )

    prompt = f"""You are an elite technical interviewer designing a structured interview plan for the following role:

JOB CONTEXT:
- Role Title: {_sanitize_untrusted(job_title)}
- Description: {_sanitize_untrusted(job_summary)}

CANDIDATE CONTEXT:
- Seniority Band: {_sanitize_untrusted(candidate_band)}
- Strengths: {_sanitize_untrusted(candidate_strengths)}
- Identified Gaps: {_sanitize_untrusted(candidate_gaps)}

QUESTION REQUIREMENTS:
You MUST generate exactly {total_requested} questions matching this exact allocation:
{slots_text}

{exclusions_text}{calibration_text}DIFFICULTY GUIDELINES:
- 'easy': One concept, answerable in 1-2 minutes. Tests foundational understanding, syntax, core mechanisms, and recall.
- 'medium': One realistic scenario and one decision, about 3-4 minutes. Tests hands-on application and practical problem-solving.
- 'hard': One design or debugging problem with trade-offs, about 6-8 minutes, still a single question. Tests architecture, performance, edge cases, and failure modes.

GENERATION RULES:
1. Ask ONE thing only, in at most two sentences (about 60 words). It must be easy to read aloud in 20 seconds.
2. Do not join two separate tasks with "and" (for example "diagnose X and design Y"). Pick the single most important task and ask only that. Follow-up details belong in key_points, not in the question.
3. Difficulty is calibrated by time:
   - easy   = one concept, answerable in 1-2 minutes.
   - medium = one realistic scenario and one decision, about 3-4 minutes.
   - hard   = one design or debugging problem with trade-offs, about 6-8 minutes, still a single question.
4. Stay inside the listed skill. A Python question must test Python itself (language, libraries, runtime), not distributed systems or databases, unless that is the listed skill.
5. key_points: 3 to 5 short sentences, each under 20 words.
6. Make questions highly practical and grounded in the realistic day-to-day duties of the {job_title} role.
7. If candidate has a gap in the requested skill, probe fundamental competence. If candidate has strong evidence, probe deeper insights.
8. Never ask generic trivia (e.g., 'What is Python?'). Focus on realistic workplace challenges.
9. Do NOT include rationale. Rationale will be computed automatically by the system.
10. Return valid JSON conforming to the requested schema.
"""
    return prompt.strip()


# ---- Prompt B: Question Regeneration -------------------------------------

def build_regeneration_prompt(
    job_title: str,
    competency: str,
    skill: str,
    difficulty: str,
    original_question: str,
    hint: Optional[str] = None,
    exclusions: Optional[List[str]] = None,
) -> str:
    """Constructs Prompt B to regenerate a single replacement question."""
    all_exclusions = list(exclusions or [])
    if original_question and original_question not in all_exclusions:
        all_exclusions.append(original_question)

    hint_instruction = ""
    if hint and hint.strip():
        hint_instruction = f"INTERVIEWER ADJUSTMENT HINT: Follow this specific interviewer request:\n\"{hint.strip()}\"\n"

    exclusions_text = ""
    if all_exclusions:
        exclusions_text = "QUESTIONS TO AVOID (DO NOT repeat or paraphrase any of these):\n" + "\n".join(
            f"- {q}" for q in all_exclusions[:20]
        ) + "\n\n"

    prompt = f"""You are an expert technical interviewer replacing an interview question.

TARGET SPECIFICATIONS:
- Role: {_sanitize_untrusted(job_title)}
- Competency: {_sanitize_untrusted(competency)}
- Skill: {_sanitize_untrusted(skill)}
- Required Difficulty: {difficulty}

ORIGINAL QUESTION (BEING REPLACED):
"{original_question}"

{hint_instruction}
{exclusions_text}REGENERATION RULES:
1. Generate exactly ONE alternative question testing the same skill '{skill}' at '{difficulty}' difficulty.
2. Ask ONE thing only, in at most two sentences (about 60 words). It must be easy to read aloud in 20 seconds.
3. Do not join two separate tasks with "and" (for example "diagnose X and design Y"). Pick the single most important task and ask only that. Follow-up details belong in key_points, not in the question.
4. Difficulty is calibrated by time:
   - easy   = one concept, answerable in 1-2 minutes.
   - medium = one realistic scenario and one decision, about 3-4 minutes.
   - hard   = one design or debugging problem with trade-offs, about 6-8 minutes, still a single question.
5. Stay inside the listed skill. A Python question must test Python itself (language, libraries, runtime), not distributed systems or databases, unless that is the listed skill.
6. key_points: 3 to 5 short sentences, each under 20 words.
7. If the interviewer hint says "more practical", use a concrete real-world scenario. Do NOT make the question longer or harder.
8. The new question must take a completely different angle, scenario, or problem structure from the original.
9. Keep the question practical and tailored to the {job_title} role.
10. Return valid JSON conforming to the schema.
"""
    return prompt.strip()


# ---- Prompt C: Skill Classification --------------------------------------

def build_skill_classification_prompt(
    skill_name: str,
    existing_competencies: List[str]
) -> str:
    """Constructs Prompt C to map an unknown skill to a standard competency."""
    comp_list = ", ".join(f"'{c}'" for c in existing_competencies)
    prompt = f"""Classify the technical skill '{skill_name}' into one of the following competencies:
{comp_list}

If it fits none well, assign a concise standard competency name. Return valid JSON with:
skill, suggested_competency, and confidence (0.0 to 1.0).
"""
    return prompt.strip()
