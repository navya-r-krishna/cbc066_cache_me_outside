import io
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def generate_plan_pdf(
    plan_data: Dict[str, Any], 
    candidate_name: str = "Candidate Profile", 
    job_title: str = "Target Role"
) -> bytes:
    """
    Generates a cleanly formatted PDF document for an interview plan.
    Returns the PDF as raw bytes.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    
    # Custom Typography Styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1E293B'),
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor('#64748B'),
        spaceAfter=12
    )
    
    competency_heading = ParagraphStyle(
        'CompHeading',
        parent=styles['Heading2'],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor('#0F172A'),
        spaceBefore=10,
        spaceAfter=6
    )

    question_style = ParagraphStyle(
        'QStyle',
        parent=styles['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#1E293B')
    )

    meta_style = ParagraphStyle(
        'MetaStyle',
        parent=styles['Normal'],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#475569')
    )

    story = []

    # Title & Header
    story.append(Paragraph(f"Interview Plan: {job_title}", title_style))
    story.append(Paragraph(f"Candidate: {candidate_name} | Generated by InterviewIQ", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#CBD5E1'), spaceAfter=12))

    questions = plan_data.get("questions", [])
    
    # Filter for active questions (accepted or pending)
    export_questions = [q for q in questions if q.get("status") in ["accepted", "pending"]]

    if not export_questions:
        story.append(Paragraph("No accepted questions found in this interview plan.", question_style))
    else:
        # Group questions by competency
        grouped = {}
        for q in export_questions:
            comp = q.get("competency", "General")
            grouped.setdefault(comp, []).append(q)

        for comp_name, q_list in grouped.items():
            story.append(Paragraph(f"Competency: {comp_name}", competency_heading))
            
            for idx, q in enumerate(q_list, 1):
                difficulty = q.get('difficulty', 'medium').upper()
                q_text = f"<b>Q{idx}. [{difficulty}]</b> {q.get('question', '')}"
                story.append(Paragraph(q_text, question_style))
                story.append(Spacer(1, 2))
                
                # Rationale & Key Points
                rationale_text = f"<i>Rationale:</i> {q.get('rationale', 'N/A')}"
                story.append(Paragraph(rationale_text, meta_style))
                
                if q.get("key_points"):
                    kp_str = " | ".join(q.get("key_points"))
                    story.append(Paragraph(f"<i>Key Points:</i> {kp_str}", meta_style))

                story.append(Spacer(1, 8))
            
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#E2E8F0'), spaceAfter=8))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes